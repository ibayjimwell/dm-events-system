import fs from 'node:fs';
import assert from 'node:assert/strict';
import {createRequire} from 'node:module';
const require=createRequire(import.meta.url);
const ts=require('typescript');
const transpile=(p)=>ts.transpileModule(fs.readFileSync(p,'utf8'),{fileName:p,compilerOptions:{module:ts.ModuleKind.CommonJS,target:ts.ScriptTarget.ES2020}}).outputText;
const permission={exports:{}};
Function('exports','require','module',transpile('src/lib/permissions.ts'))(permission.exports,require,permission);
const p=permission.exports;
assert(p.PERMISSION_KEYS.includes('bookings.create.walkin'));
assert(p.PERMISSION_KEYS.includes('packages.manage'));
assert(p.PERMISSION_KEYS.includes('analytics.view'));
assert(p.ADMIN_ONLY.has('users.manage'));
assert(p.defaultAccess('ADMIN','packages.manage'));
assert(p.defaultAccess('COORDINATOR','bookings.view.all'));
assert(!p.defaultAccess('COORDINATOR','bookings.create.walkin'));
assert(!p.defaultAccess('COORDINATOR','analytics.view'));
assert(!p.defaultAccess('CLIENT','users.manage'));
assert(p.CLIENT_IDENTITY_PERMISSIONS.has('bookings.create.own'));
for(const f of ['src/lib/access.ts','app/api/permissions/route.ts','app/api/bookings/walk-in/route.ts','app/api/bookings/[id]/status/route.ts'])assert(fs.readFileSync(f,'utf8').includes('requirePermission')||f==='src/lib/access.ts',f);
for(const perm of ['analytics.view','analytics.export','packages.manage','content.manage','settings.manage','bookings.status','calendar.view'])assert(fs.readdirSync('app/api').length>0&&fs.readFileSync('src/lib/permissions.ts','utf8').includes(perm));
const sql=fs.readFileSync('drizzle/0002_module_access_walkins.sql','utf8');
assert(sql.includes('CREATE TABLE "user_module_permissions"'));
assert(sql.includes('DROP NOT NULL'));
assert(sql.includes('ENABLE ROW LEVEL SECURITY'));
assert(sql.includes('"source"'));
console.log('PASS: permission catalog, role defaults, immutable security permission, protected API routes, and additive migration checks.');
